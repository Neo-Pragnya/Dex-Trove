"""What the trove offers for each planned capability, and what's missing (``dex capabilities``).

Curated in ``taxonomy/capabilities.yaml``. Licences are read from the catalog, never typed by hand, and every item must
exist. The published page says plainly which capabilities have nothing yet.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

import yaml

from dex_trove import catalog, releases

STATUSES = ("available", "partial", "missing")
ENHANCEMENTS = ("reuse", "sidecar", "wrapper", "workflow", "new", "feature")
STATUS_LABEL = {"available": "✅ Available", "partial": "🟡 Partial", "missing": "❌ Missing"}


class CapabilityMapError(ValueError):
    pass


def load(path: Path | None = None) -> dict[str, Any]:
    source = path or Path(__file__).resolve().parent / "taxonomy" / "capabilities.yaml"
    data: dict[str, Any] = yaml.safe_load(source.read_text(encoding="utf-8"))
    return data


def problems(data: dict[str, Any], items: list[dict[str, Any]]) -> list[str]:
    keys = {releases.key_of(i) for i in items}
    out = []
    for cid, c in data["capabilities"].items():
        if c.get("status") not in STATUSES:
            out.append(f"capability {cid}: status must be one of {', '.join(STATUSES)}")
        if c.get("enhancement") not in ENHANCEMENTS:
            out.append(f"capability {cid}: enhancement must be one of {', '.join(ENHANCEMENTS)}")
        if not str(c.get("gap") or "").strip() or not str(c.get("ananke") or "").strip():
            out.append(f"capability {cid}: gap and ananke are required")
        if c.get("enhancement") != "feature" and not c.get("existing"):
            out.append(f"capability {cid}: assess at least one existing item")
        out += [f"capability {cid}: {k} is not in the trove" for k in c.get("existing", []) if k not in keys]
    return out


def rows(data: dict[str, Any], items: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """Capabilities with each existing item's licence, from the catalog."""
    by_key = {releases.key_of(i): i for i in items}
    out = []
    for cid, c in data["capabilities"].items():
        existing = [
            {
                "key": k,
                "licence": by_key[k]["license"]["spdx"],
                "description": by_key[k].get("description") or "",
            }
            for k in c.get("existing", [])
            if k in by_key
        ]
        out.append({"id": cid, **c, "assessed": c.get("assessed", "description"), "existing": existing})
    return out


def markdown(trove: Path) -> str:
    data = load()
    table = rows(data, catalog.load(trove))
    counts = {s: sum(1 for r in table if r["status"] == s) for s in STATUSES}
    lines = [
        "---",
        "title: Capability matrix",
        "description: For each planned capability, the trove items that serve it today, their licences, what is missing, and how it will be filled.",
        "---",
        "",
        "# Capability matrix",
        "",
        "Generated by `dex docs capabilities` from `taxonomy/capabilities.yaml`; don't edit by hand. Query it with",
        "`dex capabilities`.",
        "",
        f"Of {len(table)} planned capabilities, **{counts['available']} are available**, **{counts['partial']} are partly",
        f"covered** and **{counts['missing']} have nothing that really fits yet**.",
        "",
        "Dex reuses first: an existing item is pinned and composed, a small gap gets a sidecar or a wrapper skill, and a",
        "new skill is the last resort. So a capability can be well served without a new first-party skill.",
        "",
        f"Assessed on {data['assessed_on']}. **Fit is judged from each item's own description unless marked *tests*.** No",
        "golden-task evaluation has been run, so treat `description` entries as candidates, not recommendations.",
        "",
        "| Capability | Status | Existing items | What's missing | Next step | Ananke |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for r in sorted(table, key=lambda r: (STATUSES.index(r["status"]), r["id"])):
        items = "<br>".join(f"`{e['key']}` ({e['licence']})" for e in r["existing"]) or "built into Dex"
        tested = " *(tests)*" if r["assessed"] == "tests" else ""
        lines.append(
            f"| **{r['title']}** | {STATUS_LABEL[r['status']]}{tested} | {items} | {r['gap']} | {r['enhancement']} | {r['ananke']} |"
        )
    lines += [
        "",
        "## Named upstream frameworks",
        "",
        "The plan names these for comparison. Being listed doesn't mean ingested: adding a source is a reviewed decision.",
        "",
        "| Framework | Repository | Licence | State |",
        "| --- | --- | --- | --- |",
    ]
    for f in data["frameworks"]:
        repo = f"[{f['repo']}](https://github.com/{f['repo']})" if f.get("repo") else "—"
        lines.append(f"| {f['name']} | {repo} | {f['licence']} | {f['state']} |")
    lines += [
        "",
        "See the [reuse matrix](reuse-matrix.md) for each source, and the [first-party skills](../guides/first-party-skills.md).",
        "",
    ]
    return "\n".join(lines)


__all__ = ["CapabilityMapError", "load", "markdown", "problems", "rows"]
