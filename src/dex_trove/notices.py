"""Generate THIRD_PARTY_NOTICES.md from the trove (DESIGN.md §5 Attribution)."""

from __future__ import annotations

import hashlib
from collections import defaultdict
from pathlib import Path
from typing import Any

from dex_trove import catalog
from dex_trove.licenses import LICENSE_FILE_RE
from dex_trove.sources import Source


def _licence_texts(trove: Path, item: dict[str, Any]) -> list[str]:
    d = trove / item["dir"]
    names = [f for f in item["files"] if "/" not in f and LICENSE_FILE_RE.match(f)]
    if (d / "LICENSE.upstream").is_file():
        names.append("LICENSE.upstream")
    return [(d / n).read_text(encoding="utf-8", errors="replace").strip() for n in names if (d / n).is_file()]


def render(trove: Path, sources: list[Source]) -> str:
    items = catalog.load(trove)
    by_source: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for it in items:
        by_source[it["namespace"]].append(it)
    titles = {s.id: s for s in sources}
    out = [
        "# Third-party notices",
        "",
        "Dex Trove redistributes artifacts authored by others under the licences below. Each item also keeps its",
        "own licence file (or `LICENSE.upstream`) inside its directory. Generated by `dex notices` — do not edit.",
        "",
    ]
    texts: dict[str, tuple[str, set[str]]] = {}
    for ns in sorted(by_source, key=lambda n: titles[n].priority if n in titles else 99):
        its = by_source[ns]
        src = titles.get(ns)
        out.append(f"## {src.title if src else ns}")
        out.append("")
        if src and src.web_url:
            out.append(f"Source: <{src.web_url}>  ")
        spdx: dict[str, int] = defaultdict(int)
        notices: set[str] = set()
        for it in its:
            spdx[it["license"]["spdx"]] += 1
            if it["license"].get("notice"):
                notices.update(it["license"]["notice"].splitlines())
            for text in _licence_texts(trove, it):
                h = hashlib.sha256(text.encode()).hexdigest()[:12]
                texts.setdefault(h, (text, set()))[1].add(ns)
        out.append("Licences: " + ", ".join(f"{k} ({v} items)" for k, v in sorted(spdx.items())))
        if notices:
            out.append("")
            out += [f"- {n}" for n in sorted(notices)]
        out.append("")
    out += ["## Licence texts", ""]
    for h, (text, nss) in sorted(texts.items(), key=lambda kv: (sorted(kv[1][1]), kv[0])):
        out += [f"### `{h}` — used by {', '.join(sorted(nss))}", "", "```text", text, "```", ""]
    return "\n".join(out)
