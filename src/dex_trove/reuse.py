"""docs/reference/reuse-matrix.md: how each source is reused, with the licence evidence (``dex docs reuse``).

Generated from the trove so it can't drift: tests/test_packaging.py fails when the page is stale.
"""

from __future__ import annotations

import json
from collections import Counter, defaultdict
from pathlib import Path
from typing import Any

from dex_trove import catalog, facets, relations, releases


def markdown(trove: Path) -> str:
    items = catalog.load(trove)
    excluded = json.loads((trove / "EXCLUDED.json").read_text(encoding="utf-8")).get("excluded", [])
    recs = facets.load(trove)
    typed = relations.load(trove)["items"]
    ledger = releases.load(trove)
    per: dict[str, dict[str, Any]] = defaultdict(
        lambda: {
            "kinds": Counter(),
            "licences": Counter(),
            "curated": 0,
            "relations": 0,
            "forks": 0,
            "runs": 0,
        }
    )
    for it in items:
        key = releases.key_of(it)
        row = per[it["namespace"]]
        row["kinds"][it["kind"]] += 1
        row["licences"][it["license"]["spdx"] or "unknown"] += 1
        row["curated"] += recs.get(key, {}).get("classification", {}).get("review_status") == "approved"
        row["relations"] += sum(1 for r in typed.get(key, []) if r["origin"] == "curated")
        row["forks"] += any(r.get("parent") for r in ledger["items"].get(key, {}).get("releases", []))
        row["runs"] += bool(it.get("executes_code"))
    out_reasons: dict[str, Counter[str]] = defaultdict(Counter)
    for e in excluded:
        out_reasons[e["source"]][e["reason"]] += 1
    lines = [
        "---",
        "title: Reuse matrix",
        "description: How each source is reused (as-is, enriched through sidecars, forked, or excluded) with the licence evidence.",
        "---",
        "",
        "# Reuse matrix",
        "",
        "Generated by `dex docs reuse` from the trove; don't edit by hand. Dex reuses upstream items **as-is**: the",
        "bytes are never changed. It enriches them only through **sidecars** (reviewed facets in `curation.yaml`, typed",
        "relations in `relations.yaml`) and records any **fork** in the release ledger. Everything refused is listed",
        "with its reason.",
        "",
        "| Source | Reused as-is | Kinds | Licences (evidence from licence text) | Reviewed facets | Curated relations | Forks | Bundle code | Excluded |",
        "| --- | ---: | --- | --- | ---: | ---: | ---: | ---: | ---: |",
    ]
    for ns in sorted(set(per) | set(out_reasons)):
        row = per[ns]
        kinds = ", ".join(f"{k} {n}" for k, n in sorted(row["kinds"].items()))
        lic = ", ".join(f"{k} {n}" for k, n in row["licences"].most_common())
        total = sum(row["kinds"].values())
        lines.append(
            f"| `{ns}` | {total} | {kinds or '—'} | {lic or '—'} | {row['curated']} | {row['relations']} | "
            f"{row['forks']} | {row['runs']} | {sum(out_reasons[ns].values())} |"
        )
    lines += ["", "## Why items were excluded", "", "| Source | Reason | Items |", "| --- | --- | ---: |"]
    for ns in sorted(out_reasons):
        for reason, n in out_reasons[ns].most_common():
            lines.append(f"| `{ns}` | {reason} | {n} |")
    lines += [
        "",
        "See the [licence policy](../concepts/licence-policy.md), [exclusion reasons](exclusion-reasons.md) and",
        "[related items](../concepts/related-items.md). Each item's own page shows its licence evidence and upstream",
        "commit.",
        "",
    ]
    return "\n".join(lines)


__all__ = ["markdown"]
